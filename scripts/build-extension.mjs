import { createHash } from 'node:crypto';
import { cp, mkdir, readFile, rm, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { MODEL_ID, MODEL_REVISION } from '../dist/src/cache/manifest.js';

const root = new URL('../', import.meta.url);
const source = new URL('examples/chrome-extension/', root);
const output = new URL('dist/extension/', root);
const files = ['manifest.json', 'background.js', 'content.js', 'offscreen.html', 'offscreen.js', 'options.html', 'options.js'];
// Inline execution is used, so the SDK worker and PDF assets are not needed.
const runtime = ['ort-wasm-simd-threaded.wasm', 'ort-wasm-simd-threaded.mjs', 'ort-wasm-simd-threaded.asyncify.wasm', 'ort-wasm-simd-threaded.asyncify.mjs'];

await rm(output, { recursive: true, force: true });
await mkdir(new URL('neko/assets/', output), { recursive: true });
for (const name of files) await cp(new URL(name, source), new URL(name, output));
await cp(new URL('dist/browser/neko.js', root), new URL('neko/neko.js', output));
for (const name of runtime) await cp(new URL(`dist/browser/assets/${name}`, root), new URL(`neko/assets/${name}`, output));
await writeFile(new URL('config.js', output), `// Generated by scripts/build-extension.mjs from the pinned model manifest.\nexport const DEFAULT_MODEL_BASE = ${JSON.stringify(`http://127.0.0.1:8787/models/${MODEL_ID}/${MODEL_REVISION}/`)};\n`);

// Chromium derives the extension ID from the manifest's public key: SHA-256, first 32 hex digits mapped to a-p.
const { key } = JSON.parse(await readFile(new URL('manifest.json', source), 'utf8'));
const id = [...createHash('sha256').update(Buffer.from(key, 'base64')).digest('hex').slice(0, 32)].map((digit) => String.fromCharCode(97 + Number.parseInt(digit, 16))).join('');
console.log(`Built ${fileURLToPath(output)} (extension ID ${id}).`);
console.log(`Load it unpacked from chrome://extensions, and start the model mirror with --allow-origin=chrome-extension://${id}`);
